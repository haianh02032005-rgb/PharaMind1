    SET_ONLINE = "SET_ONLINE"
    SET_OFFLINE = "SET_OFFLINE"
    OPEN_COMPARTMENT = "OPEN_COMPARTMENT"
    CLOSE_COMPARTMENT = "CLOSE_COMPARTMENT"
    SYNC_STATE = "SYNC_STATE"
