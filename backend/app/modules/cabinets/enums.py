from enum import Enum


class CabinetStatus(str, Enum):
    ONLINE = "ONLINE"
    OFFLINE = "OFFLINE"
    ERROR = "ERROR"
    MAINTENANCE = "MAINTENANCE"
    ARCHIVED = "ARCHIVED"


class HardwareMode(str, Enum):
    SIMULATOR = "SIMULATOR"
    MQTT = "MQTT"


