    EMPTY = "EMPTY"
    AVAILABLE = "AVAILABLE"
    DOSE_DUE = "DOSE_DUE"
    LOW_STOCK = "LOW_STOCK"
    EXPIRING = "EXPIRING"
    WARNING = "WARNING"
    OPEN = "OPEN"
    OFFLINE = "OFFLINE"


