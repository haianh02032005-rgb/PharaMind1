from enum import Enum


class ImportSourceType(str, Enum):
    OCR_IMAGE = "OCR_IMAGE"
    OCR_PDF = "OCR_PDF"
    EXCEL_XLSX = "EXCEL_XLSX"
    CSV = "CSV"


class ImportStatus(str, Enum):
    UPLOADED = "UPLOADED"
    PARSING = "PARSING"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"
    READY_TO_COMMIT = "READY_TO_COMMIT"
    COMMITTED = "COMMITTED"
    REJECTED = "REJECTED"
    FAILED = "FAILED"


