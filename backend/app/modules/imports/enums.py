    CREATE_NEW_PRESCRIPTION = "CREATE_NEW_PRESCRIPTION"
    UPDATE_EXISTING_PRESCRIPTION = "UPDATE_EXISTING_PRESCRIPTION"
    CREATE_MEDICATION_ONLY = "CREATE_MEDICATION_ONLY"


